/**
 * REVIEW.md and review.csv builders. Pure functions over curation results.
 */

import { hasCyrillic } from "./cleanName";
import type { Exclusion, SeedRecord } from "./curate";
import type { StapleFactors } from "./factors";

export interface Stats {
  extracted: number;
  exclusions: Exclusion[];
  duplicates: SeedRecord[];
  kept: SeedRecord[];
  factors: StapleFactors;
  factorsFileFound: boolean;
}

export function csvCell(v: string | number | null | undefined): string {
  if (v === null || v === undefined) return "";
  const s = String(v).replace(/[\r\n]+/g, " ");
  return /[",]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

const CSV_HEADER = "status,reason,code,name,brand,kcal,category,data_basis";
/** Exclusion reasons not listed row-by-row (bulk, not actionable). */
const COUNT_ONLY_REASONS = new Set(["out_of_scope", "non_hacendado_staple_not_confirmed_dry"]);

/** Numbers from the first (pre-audit) pipeline version, kept for the before/after table. */
export const BASELINE_V1 = {
  kept: 7513,
  duplicates: 4142,
  crudo: 2430,
  cocido: 21,
  nullBasis: 5062,
  crudoWithFactor: 1295,
  excluded: 6331,
} as const;

export function needsReview(r: SeedRecord): string | null {
  if (hasCyrillic(r.name)) return "cyrillic_name";
  if (r.category === null) return "category_null";
  if (r.data_basis === null) {
    const grainOrLegume = r.category === "cereales_y_granos" || r.category === "legumbres";
    if (grainOrLegume || r.basis_reason !== "no_basis_signal")
      return `basis_null:${r.basis_reason}`;
  }
  return null;
}

export function buildReviewCsv(s: Stats): string {
  const lines = [CSV_HEADER];
  for (const e of s.exclusions) {
    if (COUNT_ONLY_REASONS.has(e.reason)) continue;
    lines.push(
      ["excluded", e.reason, e.code, e.name, "", e.kcal === null ? "" : Math.round(e.kcal), "", ""]
        .map(csvCell)
        .join(",")
    );
  }
  for (const r of s.duplicates) {
    lines.push(
      [
        "duplicate",
        "dedupe_loser",
        r.code,
        r.name,
        r.brand,
        r.calories_per_100g,
        r.category,
        r.data_basis,
      ]
        .map(csvCell)
        .join(",")
    );
  }
  for (const r of s.kept) {
    const why = needsReview(r);
    if (why)
      lines.push(
        ["kept", why, r.code, r.name, r.brand, r.calories_per_100g, r.category, r.data_basis]
          .map(csvCell)
          .join(",")
      );
  }
  return `${lines.join("\n")}\n`;
}

function countBy<T>(items: T[], key: (t: T) => string): [string, number][] {
  const m = new Map<string, number>();
  for (const i of items) m.set(key(i), (m.get(key(i)) ?? 0) + 1);
  return [...m.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
}

const table = (rows: [string, number][]): string =>
  ["| value | rows |", "|---|---|", ...rows.map(([k, n]) => `| ${k} | ${n} |`)].join("\n");

export function buildReviewMd(s: Stats): string {
  const hac = s.kept.filter((r) => r.hacendado).length;
  const staples = s.kept.filter((r) => r.staple_rule !== null);
  const withFactor = s.kept.filter((r) => r.cooking_factor !== null);
  const factorLines = Object.entries(s.factors).map(
    ([k, v]) => `- \`${k}\` = ${v.factor}. Source: ${v.source}`
  );
  const reviewRows = s.kept.filter((r) => needsReview(r) !== null).length;
  return [
    "# Open Food Facts seed - review",
    "",
    "Generated by `npm run seed:hacendado`. Data: Open Food Facts (ODbL).",
    "",
    "## Counts",
    "",
    `- Extracted rows (scope file): ${s.extracted}`,
    `- Excluded by curation rules: ${s.exclusions.length}`,
    `- Duplicates dropped (same normalized name + brand): ${s.duplicates.length}`,
    `- Kept (inserted): ${s.kept.length} (Hacendado: ${hac}, other brands: ${s.kept.length - hac})`,
    `- Kept rows flagged in review.csv (NULL category or unresolved basis): ${reviewRows}`,
    "",
    "## Before / after the data-quality audit",
    "",
    "| metric | v1 (before) | now |",
    "|---|---|---|",
    `| kept rows | ${BASELINE_V1.kept} | ${s.kept.length} |`,
    `| duplicates dropped | ${BASELINE_V1.duplicates} | ${s.duplicates.length} |`,
    `| excluded rows | ${BASELINE_V1.excluded} | ${s.exclusions.length} |`,
    `| data_basis crudo | ${BASELINE_V1.crudo} | ${s.kept.filter((r) => r.data_basis === "crudo").length} |`,
    `| data_basis cocido | ${BASELINE_V1.cocido} | ${s.kept.filter((r) => r.data_basis === "cocido").length} |`,
    `| data_basis NULL | ${BASELINE_V1.nullBasis} | ${s.kept.filter((r) => r.data_basis === null).length} |`,
    `| crudo with cooking_factor | ${BASELINE_V1.crudoWithFactor} | ${withFactor.length} |`,
    "",
    "## Exclusion reasons",
    "",
    table(countBy(s.exclusions, (e) => e.reason)),
    "",
    "`out_of_scope` and `non_hacendado_staple_not_confirmed_dry` are counted only (not listed in review.csv).",
    "",
    "## Kept rows by category",
    "",
    table(countBy(s.kept, (r) => r.category ?? "NULL")),
    "",
    "## Kept rows by data_basis",
    "",
    table(countBy(s.kept, (r) => r.data_basis ?? "NULL")),
    "",
    "## Staples by rule key (dry-eligible rows)",
    "",
    table(countBy(staples, (r) => r.staple_rule ?? "")),
    "",
    "## Staples by rule key and data_basis",
    "",
    table(countBy(staples, (r) => `${r.staple_rule} / ${r.data_basis ?? "NULL"}`)),
    "",
    "## Cooking factors",
    "",
    s.factorsFileFound
      ? `Loaded from \`scripts/seed-hacendado/staple-factors.json\`; applied only to rows with data_basis = crudo and a matching rule key. Rows with a factor: ${withFactor.length}.`
      : "No staple-factors.json found: every cooking_factor is NULL.",
    "",
    ...factorLines,
    "",
    ...(s.factors.pasta_dry
      ? [
          `NOTE: the pasta_dry factor (${s.factors.pasta_dry.factor}) rests on a single egg-pasta raw/boiled pair and may overstate al-dente pasta (usually quoted around 2.2-2.5). Override it by editing that one JSON file and re-running the pipeline.`,
          "",
        ]
      : []),
    "## Known weaknesses",
    "",
    "- Category and basis rely on OFF tags, which are noisy (for example, pates carry en:pastas). Name vetoes (nameRules.ts) catch the known clashes but are a word list, not a classifier.",
    "- Tag-less Hacendado rows only get crudo through the name fallback; cooked or canned tag-less rows stay NULL.",
    "- Powdered drinks over 150 kcal/100 g are excluded, which also drops roasted coffee beans. Powders under that threshold are kept.",
    "- Dedupe merges rows with the same normalized name+brand, same data_basis and kcal within 25%; true variants that share a name and nutrition are collapsed.",
    "- Names that mix Cyrillic and Latin letters beyond lookalikes are left as-is and flagged `cyrillic_name`.",
    "- The pasta_dry factor is applied only to plain durum-wheat pasta (durum tag, or a plain pasta-shape name with no wheat-alternative evidence); wholegrain, gluten-free, legume, rice, egg-noodle and couscous rows get NULL.",
    "",
    "## Rules (summary)",
    "",
    "- Macros per 100 g from OFF; kcal 0-900, protein+carbs+fat <= 105 g, Atwater |kcal - (4P+4C+9F)| <= max(30, 25% of the larger value). Missing kcal falls back to kJ / 4.184.",
    "- data_basis `crudo` only for dry staples (no cooked/canned/fresh/dish tag) with dry energy density; `cocido` only on a cooked tag in cereales_y_granos or legumbres with cooked density; everything else NULL.",
    "- Rows with NO category tags (common for Hacendado) use a name fallback: a name starting with pasta/arroz/lentejas/garbanzos/etc. (and no cooked, prepared or filled word) plus the family dry density band gives crudo; anything else stays NULL.",
    "- Non-Hacendado products are kept only when confirmed as a dry staple.",
    "- Row-by-row listing: see review.csv (columns: status, reason, code, name, brand, kcal, category, data_basis).",
    "",
  ].join("\n");
}
